def _bundle(files: dict[str, str]) -> str:
    """The exact bytes the output digest covers: each file name, then its text."""
    return "".join(f"{name}\n{files[name]}\n" for name in sorted(files))


def starter_files(language: str) -> dict[str, str]:
    """Return the files of a starter project.

    Raises:
        ValueError: if the language is not offered.
    """
    if language == "python":
        files = {
            "main.py": _PY_MAIN,
            "requirements.txt": "vouch-protocol>=2.2\n",
            "README.md": _README.format(
                language="Python",
                run="pip install -r requirements.txt\npython main.py",
            ),
        }
    elif language == "typescript":
        files = {
            "main.ts": _TS_MAIN,
            "package.json": json.dumps(_TS_PACKAGE, indent=2) + "\n",
            "README.md": _README.format(language="TypeScript", run="npm install\nnpm start"),
        }
    else:
        raise ValueError(
            f"no starter for {language!r}; choose one of {', '.join(STARTER_LANGUAGES)}"
        )
    names = sorted([*files, "verify_assistant.py"])
    files["verify_assistant.py"] = _PY_VERIFY.replace("{FILES}", repr(names))
    return files


def bundle_for_digest(files: dict[str, str]) -> str:
    """The exact text the output digest covers: every file of the project."""
    return _bundle(files)


def build(action: str, params: dict[str, str]) -> tuple[dict[str, Any], dict[str, Any] | None, str]:
    """Build an action's output and the fields its intent will carry.

    Returns:
        (intent without outputDigest, result payload or None, text the digest covers)

    Raises:
        ValueError: for an unknown action or bad parameters.
    """
    if action == "generate_starter":
        language = params.get("language", "")
        files = starter_files(language)
        intent = {
            "action": "generate_starter",
            "target": f"starter:{language}",
            "resource": f"{ASK_URL}#starter-{language}",
        }
        return intent, {"files": files}, bundle_for_digest(files)
    if action == "sign_sample":
        intent = {
            "action": "sign_sample",
            "target": "sample",
            "resource": f"{ASK_URL}#sample",
        }
        return intent, None, "sample"
    raise ValueError(f"unknown action {action!r}")


_MARKER_RE = re.compile(
    re.escape(ACTION_MARKER)
    + r"\s*(generate_starter)\s+(python|typescript)\b|"
    + re.escape(ACTION_MARKER)
    + r"\s*(sign_sample)\b",
)


def extract_proposal(text: str) -> tuple[Proposal | None, str]:
    """Pull an action proposal marker out of a model reply.

    Returns the proposal (or None) and the reply with the marker line removed.
    Only actions and parameters on the fixed list are recognised.
    """
    match = _MARKER_RE.search(text)
    if not match:
        return None, text
    line_start = text.rfind("\n", 0, match.start()) + 1
    line_end = text.find("\n", match.end())
    cleaned = (text[:line_start] + (text[line_end + 1 :] if line_end != -1 else "")).rstrip()
    if match.group(1):
        language = match.group(2)
        label = f"Sign and generate a {'Python' if language == 'python' else 'TypeScript'} starter"
        return Proposal("generate_starter", {"language": language}, label), cleaned
    return Proposal("sign_sample", {}, "Sign a sample credential"), cleaned
